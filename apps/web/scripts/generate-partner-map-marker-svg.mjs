import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import * as icons from 'lucide-react';

const require = createRequire(import.meta.url);
const ts = require('typescript');
const directory = new URL('../src/app/(protected)/partner-map/', import.meta.url);
const names = new Set();
for (const name of ['PartnerLeafletMap.tsx', 'partner-map-icons.ts']) {
  const source = ts.createSourceFile(name, await readFile(new URL(name, directory), 'utf8'), ts.ScriptTarget.Latest, true);
  for (const node of source.statements) {
    if (!ts.isImportDeclaration(node) || node.moduleSpecifier.text !== 'lucide-react') continue;
    const bindings = node.importClause?.namedBindings;
    if (!bindings || !ts.isNamedImports(bindings)) continue;
    for (const binding of bindings.elements) {
      if (!binding.isTypeOnly) names.add((binding.propertyName ?? binding.name).text);
    }
  }
}
const sorted = [...names].sort();
const license = await readFile(new URL('../node_modules/lucide-react/LICENSE', import.meta.url), 'utf8');
const entries = sorted.map(name => {
  const markup = renderToStaticMarkup(React.createElement(icons[name], { size: 24, strokeWidth: 2, 'aria-hidden': 'true' }));
  return `  [${name}, ${JSON.stringify(markup)}],`;
});
const output = `// Generated by apps/web/scripts/generate-partner-map-marker-svg.mjs; do not edit manually.
/* Icon data license:\n${license.trim()}\n*/
import { ${sorted.join(', ')}, type LucideIcon } from "lucide-react";

const markerSvgs = new Map<LucideIcon, string>([\n${entries.join('\n')}\n]);

export function mapMarkerSvg(icon: LucideIcon, size: number, strokeWidth: number): string {
  const markup = markerSvgs.get(icon);
  if (!markup) throw new Error("Map marker SVG is missing; regenerate the marker asset.");
  return markup.replace('width="24"', 'width="' + size + '"')
    .replace('height="24"', 'height="' + size + '"')
    .replace('stroke-width="2"', 'stroke-width="' + strokeWidth + '"');
}
`;
const target = new URL('partner-map-marker-svg.ts', directory);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Map marker SVGs are stale. Run: node apps/web/scripts/generate-partner-map-marker-svg.mjs');
} else {
  await writeFile(target, output);
}
console.log(`${process.argv.includes('--check') ? 'Checked' : 'Generated'} ${sorted.length} map marker SVGs: ${fileURLToPath(target)}`);
